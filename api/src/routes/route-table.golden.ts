// Golden route tables for the Phase 4 god-file decomposition (plan §4.1).
//
// These are the ordered "METHOD path" pairs each router registers, frozen
// from the pre-split code on feat/advance-10x-phase4 (Phase 3 HEAD d16da45d)
// by reading core.ts, operations-extension.ts and control-plane.ts
// top-to-bottom in registration order. route-table.test.ts walks the live
// router stacks and asserts deep equality with these lists, so any dropped,
// duplicated, renamed or reordered route fails the build. During Phase 4
// extractions this file must not change — that is the point of the oracle.
// A deliberate route change updates the golden in the same commit as the
// route change, never inside a refactor (moves-only) commit.
//
// Paths are router-relative, exactly as registered. In api/src/index.ts the
// core and operations-extension routers mount flat at /api/v1, while the
// control-plane routers mount at /control/v1 (controlRouter), /studio/v1
// (studioRouter) and /sync/v1 (syncRouter).
//
// Count note for CORE_ROUTES: the Phase 4 plan (§1) counts 77 "route
// registrations" in core.ts. That is the number of static registration
// statements with a literal path. The live router stack has 80 entries,
// because the TEMPLATE_ROUTES loop in core.ts registers
// GET /imports/<kind>/template three times (opening-stock, sales,
// purchases) from a single statement. The golden records the stack truth:
// 77 static + 3 generated = 80. OPERATIONS_EXTENSION_ROUTES is 89, and the
// three control-plane routers total 69 (34 + 30 + 5), matching the plan.

